// Writes web/precache.js: the list of every file the service worker must cache, plus a content hash
// used as the cache version (so a new build always replaces the old cache).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..', 'web');
const SKIP = new Set(['precache.js', 'sw.js']);
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (!SKIP.has(name) && !name.endsWith('.map')) files.push(p);
  }
})(web);

const hash = createHash('sha256');
for (const f of files) hash.update(relative(web, f)).update(readFileSync(f));
hash.update(readFileSync(join(web, 'sw.js')));
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...files.map((f) => `./${relative(web, f).split('\\').join('/')}`)];
writeFileSync(join(web, 'precache.js'), `// Generated by tools/build-precache.mjs — do not edit.\nself.PRECACHE = ${JSON.stringify({ version, files: list }, null, 0)};\n`);
console.log(`precache.js: ${list.length} files, version ${version}`);

// Generates PWA icons, Android launcher icons and the demo-set figure from SVG sources.
// Usage: npm run build:icons
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const iconSvg = (pad = 0) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#337dff"/><stop offset="1" stop-color="#173cb6"/></linearGradient></defs>
  <rect width="512" height="512" rx="${pad ? 0 : 112}" fill="url(#g)"/>
  <g transform="translate(${256 - 256 * (1 - pad)} ${256 - 256 * (1 - pad)}) scale(${1 - pad})">
    <rect x="132" y="104" width="248" height="304" rx="28" fill="#fff"/>
    <rect x="164" y="146" width="132" height="18" rx="9" fill="#bcdaff"/>
    <circle cx="178" cy="214" r="14" fill="#10b981"/><rect x="204" y="206" width="140" height="16" rx="8" fill="#d9eaff"/>
    <circle cx="178" cy="266" r="14" fill="none" stroke="#94a3b8" stroke-width="6"/><rect x="204" y="258" width="120" height="16" rx="8" fill="#d9eaff"/>
    <circle cx="178" cy="318" r="14" fill="none" stroke="#94a3b8" stroke-width="6"/><rect x="204" y="310" width="132" height="16" rx="8" fill="#d9eaff"/>
    <path d="M171 214l6 6 11-12" stroke="#fff" stroke-width="5" fill="none" stroke-linecap="round" stroke-linejoin="round"/>
    <circle cx="352" cy="372" r="62" fill="#f59e0b"/>
    <path d="M326 372l18 18 34-36" stroke="#fff" stroke-width="14" fill="none" stroke-linecap="round" stroke-linejoin="round"/>
  </g></svg>`;

const out = (p) => { const f = join(root, p); mkdirSync(dirname(f), { recursive: true }); return f; };

await sharp(Buffer.from(iconSvg())).resize(192, 192).png().toFile(out('web/icons/icon-192.png'));
await sharp(Buffer.from(iconSvg())).resize(512, 512).png().toFile(out('web/icons/icon-512.png'));
await sharp(Buffer.from(iconSvg(0.18))).resize(512, 512).png().toFile(out('web/icons/maskable-512.png'));
writeFileSync(out('web/icons/icon.svg'), iconSvg());

const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, size] of Object.entries(densities)) {
  await sharp(Buffer.from(iconSvg())).resize(size, size).png().toFile(out(`android/app/src/main/res/mipmap-${d}/ic_launcher.png`));
  const roundSvg = iconSvg().replace('rx="112"', 'rx="256"');
  await sharp(Buffer.from(roundSvg)).resize(size, size).png().toFile(out(`android/app/src/main/res/mipmap-${d}/ic_launcher_round.png`));
}

// Demo figure: right-angled triangle ABC
const tri = `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="240" viewBox="0 0 360 240">
  <rect width="360" height="240" fill="#fff"/>
  <polygon points="60,30 60,200 300,200" fill="#eef6ff" stroke="#1b5ef5" stroke-width="3"/>
  <rect x="60" y="182" width="18" height="18" fill="none" stroke="#1b5ef5" stroke-width="2"/>
  <g font-family="DejaVu Sans, Arial" font-size="20" fill="#0f172a" font-weight="bold">
    <text x="40" y="28">A</text><text x="36" y="222">B</text><text x="304" y="222">C</text>
  </g>
  <g font-family="DejaVu Sans, Arial" font-size="17" fill="#b91c1c">
    <text x="12" y="120">6 cm</text><text x="160" y="226">8 cm</text><text x="190" y="105">?</text>
  </g></svg>`;
const triPng = await sharp(Buffer.from(tri)).png({ compressionLevel: 9, palette: true }).toBuffer();
writeFileSync(out('web/js/demo-figures.js'), `// Generated by tools/make-icons.mjs — do not edit.\nexport const FIG_TRIANGLE = 'data:image/png;base64,${triPng.toString('base64')}';\n`);
console.log('icons + figures generated');
